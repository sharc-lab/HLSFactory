static uint8_t xtime(uint8_t a)
{
    return (uint8_t)((a << 1) ^ ((a & 0x80) ? 0x1b : 0x00));
}

/* multiplication in GF(2^8) with the AES polynomial */
static uint8_t gmul(uint8_t a, uint8_t b)
{
    uint8_t r = 0;
    for (int i = 0; i < 8; i++) {
        if (b & 1)
            r ^= a;
        a = xtime(a);
        b >>= 1;
    }
    return r;
}

/* key expansion: AES_NR + 1 round keys of 16 bytes */
static void key_expansion(const uint8_t key[AES_KEY_SIZE],
                          uint8_t rk[(AES_NR + 1) * AES_BLOCK_SIZE])
{
    uint8_t rcon = 0x01;

    for (int i = 0; i < AES_KEY_SIZE; i++)
        rk[i] = key[i];

    for (int i = 4; i < 4 * (AES_NR + 1); i++) {
        uint8_t t[4];
        for (int j = 0; j < 4; j++)
            t[j] = rk[4 * (i - 1) + j];
        if (i % 4 == 0) {
            uint8_t tmp = t[0];
            t[0] = sbox[t[1]] ^ rcon;
            t[1] = sbox[t[2]];
            t[2] = sbox[t[3]];
            t[3] = sbox[tmp];
            rcon = xtime(rcon);
        }
        for (int j = 0; j < 4; j++)
            rk[4 * i + j] = rk[4 * (i - 4) + j] ^ t[j];
    }
}

static void add_round_key(uint8_t s[16], const uint8_t *rk)
{
    for (int i = 0; i < 16; i++)
        s[i] ^= rk[i];
}

/* state is column-major: s[4 * col + row] */
static void sub_shift(uint8_t s[16])
{
    uint8_t t[16];
    for (int c = 0; c < 4; c++)
        for (int r = 0; r < 4; r++)
            t[4 * c + r] = sbox[s[4 * ((c + r) & 3) + r]];
    for (int i = 0; i < 16; i++)
        s[i] = t[i];
}

static void inv_shift_sub(uint8_t s[16])
{
    uint8_t t[16];
    for (int c = 0; c < 4; c++)
        for (int r = 0; r < 4; r++)
            t[4 * ((c + r) & 3) + r] = inv_sbox[s[4 * c + r]];
    for (int i = 0; i < 16; i++)
        s[i] = t[i];
}

static void mix_columns(uint8_t s[16])
{
    for (int c = 0; c < 4; c++) {
        uint8_t a0 = s[4 * c], a1 = s[4 * c + 1], a2 = s[4 * c + 2], a3 = s[4 * c + 3];
        s[4 * c] = xtime(a0) ^ (xtime(a1) ^ a1) ^ a2 ^ a3;
        s[4 * c + 1] = a0 ^ xtime(a1) ^ (xtime(a2) ^ a2) ^ a3;
        s[4 * c + 2] = a0 ^ a1 ^ xtime(a2) ^ (xtime(a3) ^ a3);
        s[4 * c + 3] = (xtime(a0) ^ a0) ^ a1 ^ a2 ^ xtime(a3);
    }
}

static void inv_mix_columns(uint8_t s[16])
{
    for (int c = 0; c < 4; c++) {
        uint8_t a0 = s[4 * c], a1 = s[4 * c + 1], a2 = s[4 * c + 2], a3 = s[4 * c + 3];
        s[4 * c] = gmul(a0, 14) ^ gmul(a1, 11) ^ gmul(a2, 13) ^ gmul(a3, 9);
        s[4 * c + 1] = gmul(a0, 9) ^ gmul(a1, 14) ^ gmul(a2, 11) ^ gmul(a3, 13);
        s[4 * c + 2] = gmul(a0, 13) ^ gmul(a1, 9) ^ gmul(a2, 14) ^ gmul(a3, 11);
        s[4 * c + 3] = gmul(a0, 11) ^ gmul(a1, 13) ^ gmul(a2, 9) ^ gmul(a3, 14);
    }
}

static void encrypt_block(const uint8_t rk[(AES_NR + 1) * AES_BLOCK_SIZE],
                          const uint8_t *in, uint8_t *out)
{
    uint8_t s[16];

    for (int i = 0; i < 16; i++)
        s[i] = in[i];
    add_round_key(s, rk);
    for (int round = 1; round < AES_NR; round++) {
        sub_shift(s);
        mix_columns(s);
        add_round_key(s, rk + 16 * round);
    }
    sub_shift(s);
    add_round_key(s, rk + 16 * AES_NR);
    for (int i = 0; i < 16; i++)
        out[i] = s[i];
}

static void decrypt_block(const uint8_t rk[(AES_NR + 1) * AES_BLOCK_SIZE],
                          const uint8_t *in, uint8_t *out)
{
    uint8_t s[16];

    for (int i = 0; i < 16; i++)
        s[i] = in[i];
    add_round_key(s, rk + 16 * AES_NR);
    for (int round = AES_NR - 1; round >= 1; round--) {
        inv_shift_sub(s);
        add_round_key(s, rk + 16 * round);
        inv_mix_columns(s);
    }
    inv_shift_sub(s);
    add_round_key(s, rk);
    for (int i = 0; i < 16; i++)
        out[i] = s[i];
}

void rijndael_ecb(const uint8_t key[AES_KEY_SIZE], const uint8_t in[AES_DATA_LEN],
                  uint8_t out[AES_DATA_LEN], int decrypt)
{
    uint8_t rk[(AES_NR + 1) * AES_BLOCK_SIZE];

    key_expansion(key, rk);
    for (int b = 0; b < AES_NUM_BLOCKS; b++) {
        if (decrypt)
            decrypt_block(rk, in + AES_BLOCK_SIZE * b, out + AES_BLOCK_SIZE * b);
        else
            encrypt_block(rk, in + AES_BLOCK_SIZE * b, out + AES_BLOCK_SIZE * b);
    }
}
